FONT = dict(zip('0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ/:. ', CHARTS))
BACKGROUND, WHITE, YELLOW = (10,18,31), (224,224,224), (255,255,0)


def word(image, text, left, bottom, color):
    for index, character in enumerate(text.upper()):
        chart = FONT[character]
        for row, bits in enumerate(chart):
            for column in range(5):
                expected = color if bits & (1 << (4-column)) else BACKGROUND
                point = (left + index*6 + column, 479 - (bottom + 6-row))
                if image.getpixel(point) != expected:
                    raise ValueError(f'Visible text {text!r} differs at {point}: '
                                     f'{image.getpixel(point)} != {expected}')


def check_pixels(directory, rows, names, mode, missing):
    standings = next(row['drivers'] for row in rows if row['kind'] == 'standings')
    result = next(row for row in rows if row['kind'] == 'result')
    if len(standings) != 20:
        raise ValueError('Missing twenty-driver standings')
    # Initial division assignment is independent of the actual result ordering.
    # Stable driver ID is the original tie break after points.
    original_order = [0,6,15,12,9,17,5,18,13,19,11,2,8,14,4,10,1,16,3,7]
    initial_divisions = [3-original_order.index(driver)//5 for driver in range(20)]
    for driver, (division, rank, points) in enumerate(standings):
        expected_rank = sum(initial_divisions[rival] == division and
                            (result['drivers'][rival][3] > points or
                             (result['drivers'][rival][3] == points and rival < driver))
                            for rival in range(20))
        if division != initial_divisions[driver] or rank != expected_rank or points != result['drivers'][driver][3]:
            raise ValueError('Visible league input differs from independent score/tie ordering')
    image = Image.open(directory / 'results.ppm').convert('RGB')
    word(image, 'STOCKCAR CHAMPIONSHIP' if mode == 1 else 'WRECKING CHAMPIONSHIP', 32, 438, WHITE)
    word(image, 'ROUND COMPLETE', 32, 94, YELLOW)
    word(image, 'ENTER TO CONTINUE   ESC TO LEAVE', 32, 44, YELLOW)
    for division in range(4):
        left, bottom = 32 + (division%2)*296, 362 - (division//2)*142
        word(image, 'DIVISION', left, bottom, WHITE)
        word(image, str(division+1), left+60, bottom, WHITE)
    for driver, (division, rank, points) in enumerate(standings):
        left, bottom = 32 + (division%2)*296, 362 - (division//2)*142 - (rank+1)*18
        color = YELLOW if driver == 0 else WHITE
        word(image, str(rank+1), left, bottom, color)
        word(image, names[driver], left+18, bottom, color)
        word(image, str(points), left+228, bottom, color)
    for name, round_number, points, bottom in [('start',1,0,6), ('results',1,standings[0][2],408)]:
        current = Image.open(directory / (name+'.ppm')).convert('RGB')
        for label, value, left in [('SEASON',1,30), ('RACE',round_number,176),
                                   ('DIVISION',4,298), ('POINTS',points,440)]:
            word(current,label,left,bottom,WHITE)
            word(current,str(value),left+60,bottom,WHITE)
    if missing:
        if (directory/'results.ppm').read_bytes() != (directory/'retained.ppm').read_bytes():
            raise ValueError('Preparation failure changed visible results')
    else:
        next_image = Image.open(directory/'next.ppm').convert('RGB')
        word(next_image,'2',236,6,WHITE)
        word(next_image,str(standings[0][2]),500,6,WHITE)
    return {'pass_':True, 'all_twenty_names_ranks_scores':True,
            'metadata_round_points':True, 'preparation_rollback':missing,
            'images_sha256':{p.name:digest(p) for p in directory.glob('*.ppm')}}


